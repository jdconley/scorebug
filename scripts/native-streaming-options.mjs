import assert from 'node:assert/strict';

/** Called after continuity qualification of the known 30 fps source fixture. */
export function qualifyNativeStreamingHold({ holdSeconds, savedFrames }) {
  assert.ok(
    Number.isSafeInteger(holdSeconds) && holdSeconds >= 12 && holdSeconds <= 600,
    'Invalid hold duration',
  );
  assert.ok(Number.isSafeInteger(savedFrames) && savedFrames > 0, 'Invalid saved frame count');
  const sourceDurationSeconds = savedFrames / 30;
  assert.ok(
    sourceDurationSeconds >= holdSeconds,
    'Saved live coverage is shorter than the requested hold',
  );
  return sourceDurationSeconds;
}

/** Validated before creating native test resources; production has no hold override. */
export function nativeStreamingOptions({ streaming, environment }) {
  const raw = environment.SCOREBUG_TEST_STREAM_HOLD_SECONDS;
  if (raw === undefined) return { holdSeconds: 12, completedWindowLimit: 8, extended: false };
  assert.ok(
    streaming && environment.SCOREBUG_TEST_DIRECT_RTMP_RECORDER === '1',
    'Extended hold requires native streaming and the direct RTMP recorder',
  );
  const holdSeconds = Number(raw);
  assert.ok(
    typeof raw === 'string' &&
      /^(0|[1-9]\d*)$/.test(raw) &&
      Number.isSafeInteger(holdSeconds) &&
      holdSeconds >= 12 &&
      holdSeconds <= 600,
    'Native streaming hold must be a canonical integer from 12 through 600 seconds',
  );
  return { holdSeconds, completedWindowLimit: holdSeconds > 180 ? 128 : 64, extended: true };
}

export function nativeStreamingTestBudget(holdSeconds) {
  assert.ok(
    Number.isSafeInteger(holdSeconds) && holdSeconds >= 12 && holdSeconds <= 600,
    'Invalid hold duration',
  );
  return {
    workflowTimeoutMs: 600_000 + Math.max(0, holdSeconds - 180) * 1000,
    testExecutionAllowanceSeconds: holdSeconds > 180 ? holdSeconds + 180 : null,
  };
}

/** Explicit test workload; reject bad flags before any native resources exist. */
export function nativeFixtureWorkload({ streaming, environment }) {
  const raw = environment.SCOREBUG_TEST_MOTION_FIXTURE;
  if (raw === undefined) return 'barcode';
  assert.ok(
    raw === '1' || raw === 'blocks16',
    'Motion fixture requires exact opt-in 1 or blocks16',
  );
  assert.ok(
    streaming && environment.SCOREBUG_TEST_DIRECT_RTMP_RECORDER === '1',
    'Motion fixture requires native streaming and the direct RTMP recorder',
  );
  return raw === 'blocks16' ? 'motion-blocks16' : 'motion';
}

/** Verification strength is explicit and validated before creating fixture resources. */
export function nativeQualityOptions({ environment, requireProcessing, holdSeconds }) {
  const quality = environment.SCOREBUG_TEST_NATIVE_QUALITY;
  const confirmation = environment.SCOREBUG_TEST_NATIVE_CONFIRMATION;
  assert.ok(
    quality === undefined ||
      (quality === '1' &&
        requireProcessing &&
        holdSeconds >= 90 &&
        environment.SCOREBUG_TEST_DIRECT_RTMP_RECORDER === '1'),
    'Native quality requires exact opt-in 1, processing/publication evidence, direct recorder and at least90s hold',
  );
  assert.ok(
    confirmation === undefined || (confirmation === '1' && quality === '1'),
    'Native confirmation requires exact opt-in 1 and native quality qualification',
  );
  return { requireQuality: quality === '1', requireConfirmation: confirmation === '1' };
}

/** Publisher-only fixture route; the harness exclusively owns the generated port. */
export function nativeUplinkOptions({
  environment,
  streaming,
  requireQuality,
  requireConfirmation,
  requireProcessing,
  requirePublication,
  fixtureWorkload,
  holdSeconds,
  liveProfile = '1080p30',
}) {
  assert.ok(['1080p30', '540p30', '360p30', '240p30'].includes(liveProfile));
  assert.equal(
    environment.SCOREBUG_TEST_UPLINK_PROXY_PORT,
    undefined,
    'The uplink proxy port is generated by the native fixture, not user supplied',
  );
  const profile = environment.SCOREBUG_TEST_UPLINK_PROFILE;
  if (profile === undefined) return null;
  assert.ok(
    ['passthrough', 'rate4m', 'rate3m'].includes(profile),
    'Unsupported native uplink profile',
  );
  if (profile === 'rate3m')
    assert.ok(
      liveProfile === '240p30' && !requireQuality && !requireConfirmation,
      'The 3 Mbps qualification requires the fixed240 profile',
    );
  if (profile === 'rate4m' || profile === 'rate3m')
    assert.ok(
      Number.isSafeInteger(holdSeconds) && holdSeconds >= 180 && holdSeconds <= 600,
      'Scheduled uplink requires 180 through 600 seconds hold',
    );
  assert.ok(
    streaming &&
      ((requireQuality && requireConfirmation) ||
        (['540p30', '360p30', '240p30'].includes(liveProfile) &&
          !requireQuality &&
          !requireConfirmation &&
          environment.SCOREBUG_TEST_LIVE_PROFILE === liveProfile &&
          holdSeconds >= 90)) &&
      requireProcessing &&
      requirePublication &&
      fixtureWorkload === 'motion-blocks16' &&
      environment.SCOREBUG_TEST_DIRECT_RTMP_RECORDER === '1',
    'Uplink routing requires native quality confirmation, processing/publication, direct recorder and structured motion',
  );
  return profile;
}

/** Exact input-decoder experiment, validated before creating owned resources. */
export function fixtureDecoderThreading(environment) {
  const mode = environment.SCOREBUG_TEST_DECODER_THREADING;
  assert.ok(
    mode === undefined || ['automatic', 'slice'].includes(mode),
    'Unsupported fixture decoder threading',
  );
  return mode ?? 'automatic';
}

/** Independent requested budget, forwarded unchanged through the native test boundary. */
export function fixtureDeliveryDeadline({ environment, decoderStall }) {
  const raw = environment.SCOREBUG_TEST_DELIVERY_DEADLINE_MS;
  if (raw === undefined) return 1;
  assert.ok(
    decoderStall && ['1000', '1500'].includes(raw),
    'Unsupported controlled-fixture deadline',
  );
  return Number(raw) / 1000;
}

/** Native SDK milliseconds, not FFmpeg URL microseconds; absent preserves defaults. */
export function fixturePublishPeerLatency(environment) {
  const raw = environment.SCOREBUG_TEST_PUBLISH_PEER_LATENCY_MS;
  if (raw === undefined) return undefined;
  assert.ok(
    typeof raw === 'string' &&
      /^[1-9][0-9]*$/.test(raw) &&
      Number(raw) >= 120 &&
      Number(raw) <= 2000,
    'Unsupported fixture publish peer latency',
  );
  return Number(raw);
}

/** Explicit native relative-input pacing; absent preserves library defaults. */
export function fixturePublishPacing(environment) {
  const mode = environment.SCOREBUG_TEST_PUBLISH_PACING;
  assert.ok(mode === undefined || mode === 'relative', 'Unsupported fixture publish pacing');
  return mode;
}

/** Only the already-validated adaptive experiment may pace native encoded video. */
export function nativeSourceCadencePacing({ environment, adaptiveProfiles }) {
  const raw = environment.SCOREBUG_TEST_SOURCE_CADENCE_PACING;
  if (raw === undefined) return false;
  assert.ok(
    raw === '1' && adaptiveProfiles === true,
    'Source-cadence pacing requires exact opt-in 1 and the adaptive native fixture',
  );
  return true;
}
